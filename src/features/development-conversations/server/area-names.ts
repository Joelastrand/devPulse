import "server-only";
import { getFirestoreDb } from "../../../lib/firebase/admin";
import { isValidSkillTree } from "../../skill-trees/domain/skill-tree";
import { SHARED_GOALS_MAX } from "../domain/conversation-constants";
import type { ConversationErrorCode } from "../domain/errors";

/**
 * Resolves snapshot `treeId`s to SkillTree catalog names for the area label (SPEC BR-45, D2-SI-5). The catalog is
 * org-wide reference data, so the read is not personal. This seam is read-only: it performs point reads of
 * `skillTrees/{treeId}` only, never lists or writes the catalog, and never imports the D1 catalog seam or
 * `skill-trees/server`.
 *
 * A missing or invalid tree yields `null`, and the UI shows "area unavailable". A failed read rejects the whole call
 * with `persistence_failed`; it is never reported as an unavailable area.
 */

const SKILL_TREES_COLLECTION = "skillTrees";

/**
 * Document ids that can name a catalog tree. A `treeId` that is not addressable as a Firestore document id (empty,
 * containing `/`, a dot segment, or the reserved `__…__` form) cannot name a tree and is resolved to `null` without a
 * read. Catalog ids are generated by `collection.add`, so this never excludes a real tree. The reserved-form check
 * matches D1's `skill-catalog.ts` (`isReadableDocumentId`); without it Firestore would reject the read and the whole
 * request would fail as `persistence_failed`.
 */
const TREE_ID_SEGMENT = /^(?!__.*__$)[A-Za-z0-9_-]{1,128}$/;

/** The one read this seam needs. Returns the raw stored document data, or `undefined` when no such document exists. */
export interface SkillTreeNameReader {
  getSkillTree(treeId: string): Promise<unknown>;
}

export type AreaNamesError = Extract<ConversationErrorCode, "invalid_input" | "persistence_failed">;

export type AreaNamesResult = { ok: true; names: Map<string, string | null> } | { ok: false; error: AreaNamesError };

/**
 * Maps Firestore `Timestamp`-like `createdAt` and `updatedAt` values to `Date` so the pure validator can judge them.
 * Unexpected shapes are left as they are for the validator to reject; nothing is repaired.
 */
export function toTreeCandidate(data: unknown): unknown {
  if (typeof data !== "object" || data === null) {
    return undefined;
  }
  const record = data as Record<string, unknown>;
  return { ...record, createdAt: toDateOrRaw(record.createdAt), updatedAt: toDateOrRaw(record.updatedAt) };
}

function toDateOrRaw(value: unknown): unknown {
  if (value === undefined || value === null) {
    return undefined;
  }
  if (value instanceof Date) {
    return value;
  }
  if (typeof value === "object" && typeof (value as { toDate?: unknown }).toDate === "function") {
    return (value as { toDate(): Date }).toDate();
  }
  return value;
}

/** The validated catalog name, or `null` when the document is absent or not a valid SkillTree. */
function validTreeName(data: unknown): string | null {
  const candidate = toTreeCandidate(data);
  return isValidSkillTree(candidate) ? candidate.name : null;
}

/**
 * Returns a name per requested tree id. Input ids are deduplicated, so each distinct id is read at most once. More
 * than `SHARED_GOALS_MAX` distinct ids is rejected before any read, because a snapshot set can hold no more.
 */
export async function resolveAreaNames(
  treeIds: readonly string[],
  reader: SkillTreeNameReader = createFirestoreSkillTreeNameReader(),
): Promise<AreaNamesResult> {
  const distinct = [...new Set(treeIds)];
  if (distinct.length > SHARED_GOALS_MAX) {
    return { ok: false, error: "invalid_input" };
  }

  const names = new Map<string, string | null>();
  for (const treeId of distinct) {
    if (!TREE_ID_SEGMENT.test(treeId)) {
      names.set(treeId, null);
      continue;
    }
    let data: unknown;
    try {
      data = await reader.getSkillTree(treeId);
    } catch {
      return { ok: false, error: "persistence_failed" };
    }
    names.set(treeId, validTreeName(data));
  }

  return { ok: true, names };
}

/** Production reader: one point read per tree through the centralized Admin SDK initialization. */
export function createFirestoreSkillTreeNameReader(): SkillTreeNameReader {
  return {
    async getSkillTree(treeId) {
      const snapshot = await getFirestoreDb().collection(SKILL_TREES_COLLECTION).doc(treeId).get();
      return snapshot.exists ? snapshot.data() : undefined;
    },
  };
}
